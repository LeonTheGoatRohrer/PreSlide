"""Read-only local API exposing aggregate results and five allowlisted examples."""
from pathlib import Path
from functools import lru_cache
from fastapi import FastAPI,HTTPException
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from .common import read_json
from .sources import ROOT

app=FastAPI(title='Talwacht – lokaler Forschungsprototyp',docs_url=None,redoc_url=None)

@lru_cache(maxsize=1)
def demo_directory():
    pointer=ROOT/'data/processed/demo.json'
    if not pointer.exists(): raise HTTPException(503,'Demo noch nicht vorbereitet: python -m preslide.demo')
    directory=Path(read_json(pointer)['directory']).resolve()
    if not directory.is_relative_to((ROOT/'data/processed').resolve()): raise HTTPException(500,'Ungültiger Demo-Pfad')
    return directory

def case_path(case_id,suffix):
    allowed={r['id'] for r in read_json(demo_directory()/'cases.json')}
    if case_id not in allowed: raise HTTPException(404,'Unbekanntes Demonstrationsbeispiel')
    return demo_directory()/f'{case_id}.{suffix}'

@app.get('/api/health')
def health():
    return {'status':'ok','mode':'local_research','raw_data_exposed':False}

