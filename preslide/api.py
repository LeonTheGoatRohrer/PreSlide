@app.get('/api/cases/{case_id}')
def case(case_id:str):
    return read_json(case_path(case_id,'json'))

@app.get('/api/cases/{case_id}/terrain.png')
def terrain_image(case_id:str):
    return FileResponse(case_path(case_id,'png'),media_type='image/png',headers={'Cache-Control':'private, max-age=3600'})

STABILITY_FIGURES = {
    'A_performance', 'B_weather_delta', 'C_event_ranks', 'D_learning_curve',
    'E_weather_differences', 'F_feature_stability', 'G_storm_sensitivity',
}


@app.get('/api/stability/figures/{figure}.png')
def stability_figure(figure: str):
    if figure not in STABILITY_FIGURES:
        raise HTTPException(404, 'Unbekannte Abbildung')
    directory = ROOT/'reports/stability_v02'
    verification = directory/'verification.json'
    if not verification.exists() or read_json(verification).get('status') != 'PASS':
        raise HTTPException(503, 'Stabilitätsanalyse noch nicht abschließend geprüft.')
    return FileResponse(directory/(figure+'.png'), media_type='image/png')


